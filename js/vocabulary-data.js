export const VOCAB_CATEGORY_BY_ID = Object.fromEntries(
  VOCAB_CATEGORIES.map((category) => [category.id, category])
);

export const VOCAB_LEVEL_BY_ID = Object.fromEntries(
  VOCAB_LEVELS.map((level) => [level.id, level])
);

export const VOCAB_LETTERS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ".split("");

/** Stable, readable DOM id for a term. */
export function vocabId(term) {
  return `vocab-${term
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")}`;
}

/** Alphabetical sort that ignores leading articles and case. */
export function sortVocabulary(entries = VOCABULARY) {
  return [...entries].sort((a, b) =>
    a.term.localeCompare(b.term, "en", { sensitivity: "base" })
  );
}

// Let a student type the glyph itself (∠, ⊥, ≅) as well as its LaTeX command.
const SYMBOL_GLYPHS = [
  ["\\cong", "≅"],
  ["\\sim", "∼"],
  ["\\angle", "∠"],
  ["\\triangle", "△"],
  ["\\perp", "⊥"],
  ["\\parallel", "∥"],
  ["\\neq", "≠"],
  ["\\le", "≤"],
  ["\\ge", "≥"],
  ["\\pm", "±"],
  ["\\therefore", "∴"],
  ["\\because", "∵"],
  ["\\Rightarrow", "⇒"],
  ["\\Leftrightarrow", "⇔"],
  ["\\in", "∈"],
  ["\\notin", "∉"],
  ["\\subset", "⊂"],
  ["\\cup", "∪"],
  ["\\cap", "∩"],
  ["\\varnothing", "∅"],
  ["\\infty", "∞"],
  ["\\sum", "∑"],
  ["\\pi", "π"],
  ["\\approx", "≈"],
  ["\\equiv", "≡"],
];

/** The Unicode glyph for a LaTeX symbol, when one is commonly used. */
export function vocabSymbolGlyph(symbol) {
  if (!symbol) return "";
  return SYMBOL_GLYPHS.find(([command]) => symbol.includes(command))?.[1] ?? "";
}

/** Everything a search should be able to match for one entry. */
export function vocabSearchText(entry) {
  const category = VOCAB_CATEGORY_BY_ID[entry.category]?.label ?? "";
  const level = VOCAB_LEVEL_BY_ID[entry.level]?.label ?? "";
  return [
    entry.term,
    entry.symbol ?? "",
    vocabSymbolGlyph(entry.symbol),
    ...(entry.aliases ?? []),
    entry.simple,
    entry.formal,
    entry.example ?? "",
    category,
    level,
  ]
    .join(" ")
    .toLowerCase();
}
